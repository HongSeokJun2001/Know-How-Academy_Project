--반 테이블
CREATE TABLE CLASS (
  CLASS_NO NUMBER PRIMARY KEY,
  CLASS_NAME VARCHAR2(100) NOT NULL,
  DESCRIPTION VARCHAR2(500),
  STATUS VARCHAR2(1) DEFAULT 'N' NOT NULL CHECK(STATUS IN('Y', 'N')),
  CREATED_AT DATE DEFAULT SYSDATE,
  UPDATED_AT DATE DEFAULT SYSDATE
);

COMMENT ON COLUMN CLASS.CLASS_NO IS '반번호';
COMMENT ON COLUMN CLASS.CLASS_NAME IS '반이름';
COMMENT ON COLUMN CLASS.DESCRIPTION IS '반설명';
COMMENT ON COLUMN CLASS.STATUS IS '사용상태';
COMMENT ON COLUMN CLASS.CREATED_AT IS '생성일';
COMMENT ON COLUMN CLASS.UPDATED_AT IS '수정일';

-- 회원 테이블
CREATE TABLE MEMBER (
  USER_NO NUMBER PRIMARY KEY,
  USER_ID VARCHAR2(50) NOT NULL,
  USER_PWD VARCHAR2(200) NOT NULL,
  USER_NAME VARCHAR2(20) NOT NULL,
  PHONE VARCHAR2(20),
  EMAIL VARCHAR2(100) NOT NULL,
  ADDRESS VARCHAR2(300),
  ROLE_CODE VARCHAR2(20) NOT NULL,
  STATUS VARCHAR2(20),
  CREATED_AT DATE,
  UPDATED_AT DATE,
  CLASS_NO NUMBER,
  FOREIGN KEY(CLASS_NO) REFERENCES CLASS(CLASS_NO)
);

